namespace Lark\Services\Application;

use Lark\Api\Application\App\ApplicationV2AppVisibility;
use Lark\Api\Application\App\ApplicationV3AppList;
use Lark\Api\Application\App\ApplicationV3AppUpdateVisibility;
use Lark\LarkClient;

final class AppResource
{
    public function __construct(
        private readonly LarkClient $client
    ) {
    }
    /**
     * @param array<string, mixed> $pathParams
     * @param array<string, mixed> $query
     * @param array<string, mixed> $payload
     * @param array<string, mixed> $options
     *
     * @return array<string, mixed>
     */
    public function getVisibility(
        array $pathParams = [],
        array $query = [],
        array $payload = [],
        ?string $accessToken = null,
        array $options = []
    ): array {
        return $this->client->send(
            new ApplicationV2AppVisibility(),
            $pathParams,
            $query,
            $payload,
            $accessToken,
            $options
        );
    }

    /**
     * @param array<string, mixed> $pathParams
     * @param array<string, mixed> $query
     * @param array<string, mixed> $payload
     * @param array<string, mixed> $options
     *
     * @return array<string, mixed>
     */
    public function list(
        array $pathParams = [],
        array $query = [],
        array $payload = [],
        ?string $accessToken = null,
        array $options = []
    ): array {
        return $this->client->send(
            new ApplicationV3AppList(),
            $pathParams,
            $query,
            $payload,
            $accessToken,
            $options
        );
    }

    /**
     * @param array<string, mixed> $pathParams
     * @param array<string, mixed> $query
     * @param array<string, mixed> $payload
     * @param array<string, mixed> $options
     *
     * @return array<string, mixed>
     */
    public function updateVisibility(
        array $pathParams = [],
        array $query = [],
        array $payload = [],
        ?string $accessToken = null,
        array $options = []
    ): array {
        return $this->client->send(
            new ApplicationV3AppUpdateVisibility(),
            $pathParams,
            $query,
            $payload,
            $accessToken,
            $options
        );
    }
}
